                    <p>
                        Pendant ma deuxième année de BTS, j'ai réalisé un second stage en entreprise du 8 janvier au 23
                        février 2024.
                        L'application sur laquelle j'ai travaillé est appelée "Soprano V2", elle utilise le FrameWork
                        Angular pour le Front et
                        SpringBoot pour le Back. J'ai donc découvert deux nouvelles technologies que je ne connaissais
                        que de nom auparavant.
                        L'application Soprano permet principalement d'ajouter des produits à des propositions et/ou
                        contrat clients. Si une entreprise souhaite assurer ses salariés,
                        elle peut contacter Harmonie Mutuelle. À ce moment précis Harmonie mutuelle crée alors une
                        proposition à laquelle des produits seront ajoutés.
                        Une fois le client satisfait, un contrat est ainsi signé.

                    </p>
                </div>
                <br>
                <div class="obj">
                    <h5><u>Objectif : </u></h5><br>
                    <p>
                        Mon objectif principal a donc été d'ajouter une fonctionnalité à cette application.
                        La fonctionnalité doit permettre aux commerciaux de vérifier si un produit n'est pas déja
                        utilisé sur une proposition ou un contrat.
                        Si c'est le cas, alors ils seront affichés pour prévenir le commercial.

                    </p>
