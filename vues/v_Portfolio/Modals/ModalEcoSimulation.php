                <div class="description">
                    <h5><u>Description du projet</u></h5><br>
                    <p>
                        Lors du quatrième semestre, nous avons réalisé par groupe de 2, un projet appelé "Ecoert
                        Simulateur". Celui-ci avait pour but de nous former à la création de page web avec Java et
                        notamment
                        JSP. Nous avons aussi utilisé Hibernate, qui nous a permis de créer notre base de données via
                        des annotations dans nos classes Metiers. SQL Server a aussi était utilisé pour stocker les
                        différentes données.
                    </p>
